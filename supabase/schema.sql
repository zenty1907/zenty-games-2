-- Zenty Place: Supabase/Postgres schema
-- Run this in Supabase Dashboard -> SQL Editor after creating a project.
create extension if not exists pgcrypto;

create table if not exists public.pixels (
  id bigint generated by default as identity primary key,
  x integer not null,
  y integer not null,
  color text not null check (color ~ '^#[0-9A-Fa-f]{6}$'),
  user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (x, y)
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (char_length(username) between 3 and 20),
  pixels_placed integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  code text not null unique default upper(substr(encode(gen_random_bytes(6), 'hex'), 1, 8)),
  name text not null check (char_length(name) between 2 and 32),
  owner_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.team_members (
  team_id uuid not null references public.teams(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (team_id, user_id)
);

create index if not exists pixels_created_at_idx on public.pixels(created_at desc);
create index if not exists pixels_user_id_idx on public.pixels(user_id);
create index if not exists team_members_user_id_idx on public.team_members(user_id);

alter table public.pixels enable row level security;
alter table public.profiles enable row level security;
alter table public.teams enable row level security;
alter table public.team_members enable row level security;

-- Anyone can read the shared canvas and public profile/team data.
drop policy if exists "pixels are publicly readable" on public.pixels;
create policy "pixels are publicly readable" on public.pixels for select to anon, authenticated using (true);
drop policy if exists "profiles are publicly readable" on public.profiles;
create policy "profiles are publicly readable" on public.profiles for select to anon, authenticated using (true);
drop policy if exists "teams are publicly readable" on public.teams;
create policy "teams are publicly readable" on public.teams for select to anon, authenticated using (true);
drop policy if exists "team members are publicly readable" on public.team_members;
create policy "team members are publicly readable" on public.team_members for select to anon, authenticated using (true);

-- Pixel placement must go through place_pixel(), never direct client inserts.
drop policy if exists "no direct pixel inserts" on public.pixels;
create policy "no direct pixel inserts" on public.pixels for insert to authenticated with check (false);
drop policy if exists "no direct pixel updates" on public.pixels;
create policy "no direct pixel updates" on public.pixels for update to authenticated using (false);
drop policy if exists "no direct pixel deletes" on public.pixels;
create policy "no direct pixel deletes" on public.pixels for delete to authenticated using (false);

drop policy if exists "users manage own profile" on public.profiles;
create policy "users manage own profile" on public.profiles for insert to authenticated with check (id = auth.uid());
drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "signed-in users create teams" on public.teams;
create policy "signed-in users create teams" on public.teams for insert to authenticated with check (owner_id = auth.uid());
drop policy if exists "owners update teams" on public.teams;
create policy "owners update teams" on public.teams for update to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());
drop policy if exists "users join themselves" on public.team_members;
create policy "users join themselves" on public.team_members for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "users leave themselves" on public.team_members;
create policy "users leave themselves" on public.team_members for delete to authenticated using (user_id = auth.uid());

-- Atomic cooldown + pixel upsert. Enforces 30 seconds on the server, not the browser.
create table if not exists public.pixel_cooldowns (
  user_id uuid primary key references auth.users(id) on delete cascade,
  next_pixel_at timestamptz not null default now()
);
alter table public.pixel_cooldowns enable row level security;

create or replace function public.place_pixel(p_x integer, p_y integer, p_color text)
returns public.pixels
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_next timestamptz;
  v_pixel public.pixels;
begin
  if v_user is null then
    raise exception 'Giriş yapmalısın.' using errcode = '28000';
  end if;
  if p_x < -180000 or p_x > 180000 or p_y < -85000 or p_y > 85000 then
    raise exception 'Koordinat geçersiz.';
  end if;
  if p_color !~ '^#[0-9A-Fa-f]{6}$' then
    raise exception 'Renk geçersiz.';
  end if;

  insert into public.pixel_cooldowns(user_id, next_pixel_at)
  values (v_user, now())
  on conflict (user_id) do nothing;

  select next_pixel_at into v_next
  from public.pixel_cooldowns where user_id = v_user for update;

  if v_next > now() then
    raise exception 'Piksel hakkın henüz yenilenmedi.' using errcode = 'P0001';
  end if;

  update public.pixel_cooldowns
  set next_pixel_at = now() + interval '30 seconds'
  where user_id = v_user;

  insert into public.pixels(x, y, color, user_id)
  values (p_x, p_y, p_color, v_user)
  on conflict (x, y) do update
    set color = excluded.color, user_id = excluded.user_id, created_at = now()
  returning * into v_pixel;

  update public.profiles set pixels_placed = pixels_placed + 1 where id = v_user;
  return v_pixel;
end;
$$;

revoke all on function public.place_pixel(integer, integer, text) from public;
grant execute on function public.place_pixel(integer, integer, text) to authenticated;

-- Realtime sync for the shared canvas.
alter publication supabase_realtime add table public.pixels;
